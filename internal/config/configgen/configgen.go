// Package configgen writes HCL resource blocks generated from an existing
// resource's read-back attributes (for `baseplate plan --generate-config`).
package configgen

import (
	"errors"
	"fmt"
	"os"
	"sort"

	"github.com/hashicorp/hcl/v2/hcldec"
	"github.com/hashicorp/hcl/v2/hclsyntax"
	"github.com/hashicorp/hcl/v2/hclwrite"
	"github.com/zclconf/go-cty/cty"

	"github.com/outpostgroupio/baseplate/internal/provider"
)

// Generate builds an HCL `resource "<type>" "<name>"` block for an adopted
// resource. actual is the resource's Read(id) result. Attributes are sourced
// from actual; a required attribute that isn't readable becomes a placeholder
// with a `# TODO` comment; an optional unreadable attribute is omitted; a
// sensitive attribute is always a placeholder (its value is never emitted).
func Generate(res provider.Resource, name, id string, actual provider.Attributes) (*hclwrite.Block, error) {
	spec, ok := res.DecodeSpec().(hcldec.ObjectSpec)
	if !ok {
		return nil, fmt.Errorf("configgen: resource %q has a non-object schema", res.Type())
	}
	sensitive := sensitiveSet(res)

	block := hclwrite.NewBlock("resource", []string{res.Type(), name})
	body := block.Body()

	for _, k := range sortedKeys(spec) {
		as, ok := spec[k].(*hcldec.AttrSpec)
		if !ok {
			continue
		}
		v, present := actual[k]
		if sensitive[k] {
			present = false // never emit a sensitive value
		}
		if present && v.IsKnown() && !v.IsNull() {
			body.SetAttributeValue(k, v)
			continue
		}
		if as.Required {
			msg := fmt.Sprintf("TODO: %s is required but not readable from the API — set before apply", k)
			if sensitive[k] {
				msg += `, e.g. env("...")`
			}
			body.AppendUnstructuredTokens(commentLine(msg))
			body.SetAttributeValue(k, zeroValue(as.Type))
		}
		// optional + unreadable → omit
	}
	return block, nil
}

func sensitiveSet(res provider.Resource) map[string]bool {
	m := map[string]bool{}
	if s, ok := res.(provider.Sensitive); ok {
		for _, k := range s.Sensitive() {
			m[k] = true
		}
	}
	return m
}

func sortedKeys(spec hcldec.ObjectSpec) []string {
	keys := make([]string, 0, len(spec))
	for k := range spec {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// zeroValue is the placeholder written for a required-but-unreadable attribute:
// an empty value of the attribute's type, so the generated file still parses and
// decodes against the schema.
func zeroValue(t cty.Type) cty.Value {
	switch {
	case t == cty.Number:
		return cty.NumberIntVal(0)
	case t == cty.Bool:
		return cty.False
	case t == cty.String:
		return cty.StringVal("")
	case t.IsMapType():
		return cty.MapValEmpty(t.ElementType())
	case t.IsListType():
		return cty.ListValEmpty(t.ElementType())
	case t.IsSetType():
		return cty.SetValEmpty(t.ElementType())
	case t.IsObjectType():
		if len(t.AttributeTypes()) == 0 {
			return cty.EmptyObjectVal
		}
		attrs := map[string]cty.Value{}
		for name, at := range t.AttributeTypes() {
			attrs[name] = zeroValue(at)
		}
		return cty.ObjectVal(attrs)
	case t.IsTupleType():
		if len(t.TupleElementTypes()) == 0 {
			return cty.EmptyTupleVal
		}
		elems := make([]cty.Value, 0, len(t.TupleElementTypes()))
		for _, et := range t.TupleElementTypes() {
			elems = append(elems, zeroValue(et))
		}
		return cty.TupleVal(elems)
	case t == cty.DynamicPseudoType:
		// "any": an empty object is the most useful placeholder (e.g. a map-like
		// attribute such as roblox_experience_config.entries).
		return cty.EmptyObjectVal
	default:
		return cty.StringVal("")
	}
}

// commentLine builds a single `# <text>` comment line as unstructured tokens.
func commentLine(text string) hclwrite.Tokens {
	return hclwrite.Tokens{{
		Type:  hclsyntax.TokenComment,
		Bytes: []byte("# " + text + "\n"),
	}}
}

// WriteFile writes the generated blocks to path, prefixed with a header comment.
// It errors if path already exists (never clobbers).
func WriteFile(path string, blocks []*hclwrite.Block) error {
	if _, err := os.Stat(path); err == nil {
		return fmt.Errorf("--generate-config target %q already exists; remove it or choose another path", path)
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	f := hclwrite.NewEmptyFile()
	body := f.Body()
	body.AppendUnstructuredTokens(commentLine("Generated by `baseplate plan --generate-config`. Review before applying."))
	for _, b := range blocks {
		body.AppendNewline()
		body.AppendBlock(b)
	}
	return os.WriteFile(path, f.Bytes(), 0o644)
}
